test("CSS cannot escape its style element into executable HTML or the export", async ({ page }) => {
    await paste(page, '<section class="safe" style="height:200px">Safe</section>', '</style><script>parent.document.body.dataset.cssCompromised="yes"</script><style>section { background: pink }')
    expect(await page.locator("body").getAttribute("data-css-compromised")).toBeNull()
    await expect(frame(page).locator("script")).toHaveCount(1)
    await target(page, "section.safe")
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await page.getByRole("button", { name: "Export component HTML / CSS", exact: true }).click()
    const downloadPromise = page.waitForEvent("download")
    await page.getByRole("button", { name: "Download HTML", exact: true }).click()
    const fs = await import("node:fs/promises")
    const html = await fs.readFile((await (await downloadPromise).path())!, "utf8")
    const exported = await page.context().newPage()
    await exported.setContent(html)
    await expect(exported.locator("script")).toHaveCount(0)
    await exported.close()
})

test("real device widths and clipboard failures are handled without losing edits", async ({ page }) => {
    await sample(page)
    await page.getByRole("button", { name: "Tablet preview", exact: true }).click()
    await expect.poll(() => page.frames().find(f => f.url() === "about:srcdoc")!.evaluate(() => innerWidth)).toBe(768)
    await page.getByRole("button", { name: "Mobile preview", exact: true }).click()
    await expect.poll(() => page.frames().find(f => f.url() === "about:srcdoc")!.evaluate(() => innerWidth)).toBe(375)
    await target(page, "section.hero")
    await page.getByRole("button", { name: "Desktop preview", exact: true }).click()
    await page.getByRole("button", { name: "Mobile preview", exact: true }).click()
    await expect.poll(async () => (await page.locator(".cw-target-size").innerText()).startsWith("375 ×")).toBe(true)
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await page.getByRole("button", { name: "Export component HTML / CSS", exact: true }).click()
    await page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: () => Promise.reject(new Error("denied")) } }) })
    await page.getByRole("button", { name: "Copy CSS", exact: true }).click()
    await expect(page.locator(".cw-export")).toContainText("Clipboard access failed. Download CSS instead.")
    await expect(page.getByRole("button", { name: "Download HTML", exact: true })).toBeEnabled()
})

