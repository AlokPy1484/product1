import { test, expect, type Page } from "@playwright/test"

const frame = (page: Page) => page.frameLocator('iframe[title="Component preview"]')
async function open(page: Page) {
    await page.goto("/")
    await page.getByRole("button", { name: "Upload component", exact: true }).click()
    await expect(page.getByRole("heading", { name: "Your component. Your pattern." })).toBeVisible()
}
async function sample(page: Page, name = "Landing hero") {
    await open(page)
    await page.getByRole("button", { name: new RegExp(name) }).click()
    await expect(page.locator("#cw-target option")).not.toHaveCount(1)
}
async function target(page: Page, label: string) {
    const option = page.locator("#cw-target option").filter({ hasText: label }).first()
    await page.locator("#cw-target").selectOption((await option.getAttribute("value"))!)
}
async function paste(page: Page, html: string, css = "") {
    await open(page)
    await page.getByRole("tab", { name: "Paste code" }).click()
    await page.getByLabel("HTML", { exact: true }).fill(html)
    if (css) await page.getByLabel("CSS (optional)", { exact: true }).fill(css)
    await page.getByRole("button", { name: "Preview component", exact: true }).click()
    await expect(page.locator("#cw-target option")).not.toHaveCount(1)
}

test.beforeEach(async ({ page }) => { await page.addInitScript(() => { if (window === window.top) localStorage.setItem("hasVisited", "true") }) })

test("home keeps its canvas settings and only opens the feature on demand", async ({ page }) => {
    await page.goto("/")
    await expect(page.getByRole("button", { name: "Upload component", exact: true })).toBeVisible()
    await expect(page.locator(".component-workspace")).toHaveCount(0)
    const before = await page.locator("[data-pattern-background] > div").last().getAttribute("style")
    const savedBefore = await page.evaluate(() => localStorage.getItem("dotgrid:pattern-layers:v2"))
    await page.getByRole("button", { name: "Upload component", exact: true }).click()
    await page.getByRole("button", { name: /Landing hero/ }).click()
    await target(page, "section.hero")
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await page.locator(".component-workspace").getByLabel("Primary colour", { exact: true }).fill("#ff0000")
    await page.getByRole("button", { name: "Back to pattern canvas" }).click()
    await expect(page.locator(".component-workspace")).toHaveCount(0)
    expect(await page.evaluate(() => localStorage.getItem("dotgrid:pattern-layers:v2"))).toBe(savedBefore)
    expect(await page.locator("[data-pattern-background] > div").last().getAttribute("style")).toBe(before)
})

test("selects nested targets, edits independently without reloading, and restores inline backgrounds", async ({ page }) => {
    await paste(page, '<section id="hero" style="height:300px;background:red!important;padding:30px"><div class="card" style="height:100px;background:blue">Card</div></section>')
    await frame(page).locator(".card").click()
    await expect(page.locator(".cw-target-info code")).toHaveText("div.card")
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await expect(frame(page).locator(".card")).toHaveCSS("background-image", /radial-gradient/)
    await page.locator(".component-workspace").getByLabel("Primary colour", { exact: true }).fill("#123456")
    await expect(frame(page).locator(".card")).toHaveCSS("background-image", /18, 52, 86/)
    await page.getByRole("button", { name: "Parent", exact: true }).click()
    await expect(page.locator(".cw-target-info code")).toHaveText("section#hero")
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await page.locator(".component-workspace").getByRole("button", { name: "Choose preset", exact: true }).click()
    await page.getByRole("menuitem", { name: "Grid Preset 1", exact: true }).click()
    await expect(frame(page).locator("#hero")).toHaveCSS("background-image", /repeating-linear-gradient/)
    await expect(frame(page).locator(".card")).toHaveCSS("background-image", /radial-gradient/)
    const session = await page.locator("iframe").getAttribute("srcdoc")
    await page.getByRole("button", { name: "Restore original background" }).click()
    await expect(frame(page).locator("#hero")).toHaveCSS("background-color", "rgb(255, 0, 0)")
    await expect(frame(page).locator("#hero")).toHaveCSS("background-image", "none")
    expect(await page.locator("iframe").getAttribute("srcdoc")).toBe(session)
})

test("upload accepts HTML and CSS, reports unsupported files and oversize input", async ({ page }) => {
    await open(page)
    const input = page.getByLabel("Component files")
    await input.setInputFiles({ name: "bad.js", mimeType: "text/javascript", buffer: Buffer.from("alert(1)") })
    await expect(page.locator(".cw-error[role=alert]")).toContainText("HTML file")
    await input.setInputFiles({ name: "large.html", mimeType: "text/html", buffer: Buffer.alloc(2 * 1024 * 1024 + 1, "x") })
    await expect(page.locator(".cw-error[role=alert]")).toContainText("2 MB")
    await input.setInputFiles([{ name: "uploaded.html", mimeType: "text/html", buffer: Buffer.from('<section class="uploaded">Uploaded</section>') }, { name: "uploaded.css", mimeType: "text/css", buffer: Buffer.from(".uploaded { padding: 40px; background: rgb(12, 34, 56) }") }])
    await page.getByRole("button", { name: "Preview component", exact: true }).click()
    await expect(frame(page).locator(".uploaded")).toHaveCSS("background-color", "rgb(12, 34, 56)")
    await expect(page.locator(".cw-filename")).toContainText("uploaded.html")
})

test("sandbox blocks uploaded scripts, network assets and navigation, while trusted picking still works", async ({ page }) => {
    const requests: string[] = []
    await page.route("https://assets.example.test/**", route => { requests.push(route.request().url()); return route.fulfill({ body: "", status: 200 }) })
    await paste(page, `<script>parent.document.body.dataset.compromised='yes';</script><style>@import url('https://assets.example.test/a.css');</style><meta http-equiv="refresh" content="0;url=https://assets.example.test"><iframe src="https://assets.example.test"></iframe><section id="safe" onmouseover="parent.alert('bad')" style="height:300px"><img src="https://assets.example.test/a.png"><a href="https://assets.example.test/leave">Leave</a><form action="https://assets.example.test"><button>Submit</button></form></section>`)
    const iframe = page.locator('iframe[title="Component preview"]')
    await expect(iframe).toHaveAttribute("sandbox", "allow-scripts")
    expect(await page.locator("body").getAttribute("data-compromised")).toBeNull()
    await expect(frame(page).locator("script:not([nonce])")).toHaveCount(0)
    await expect(frame(page).locator("iframe, [onmouseover]")).toHaveCount(0)
    await page.getByRole("button", { name: "Select element", exact: true }).click()
    await frame(page).getByRole("link", { name: "Leave" }).click()
    await frame(page).getByRole("button", { name: "Submit" }).click()
    expect(requests).toEqual([])
    await expect(frame(page).locator("#safe")).toBeVisible()
    await page.getByRole("button", { name: "Select element", exact: true }).click()
    await frame(page).locator("#safe").click({ position: { x: 100, y: 200 } })
    await expect(page.locator(".cw-target-info code")).toHaveText("section#safe")
})

test("exports matching CSS and clean static HTML with working background classes", async ({ page }) => {
    await sample(page)
    await target(page, "section.hero")
    await page.getByRole("button", { name: "Apply pattern", exact: true }).click()
    await page.getByRole("button", { name: "Export component HTML / CSS", exact: true }).click()
    const css = await page.locator(".cw-export pre").innerText()
    expect(css).toContain(".dotgrid-bg-")
    expect(css).toContain("background-image: radial-gradient")
    const downloadPromise = page.waitForEvent("download")
    await page.getByRole("button", { name: "Download HTML", exact: true }).click()
    const download = await downloadPromise
    const fs = await import("node:fs/promises")
    const html = await fs.readFile((await download.path())!, "utf8")
    expect(html).toContain(css)
    expect(html).not.toContain("data-dotgrid-target")
    expect(html).not.toContain("dotgrid:connect")
    expect(html).not.toContain("<script")
    expect(html).toMatch(/class="hero dotgrid-bg-/)
})

